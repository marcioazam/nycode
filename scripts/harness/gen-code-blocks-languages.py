#!/usr/bin/env python3
"""Gera packages/coding-agent/src/extensions/code-blocks/languages.ts a partir do github-linguist/linguist lib/linguist/languages.yml.

Uso: python3 scripts/harness/gen-code-blocks-languages.py [languages.yml]  (sem argumento baixa a versão atual do main).
Saída: {"source", "langs": [[nome, cor|null, [candidatos de gramática]]], "tags": {etiqueta: índice}}.
Precedência das etiquetas: nome > alias > extensão primária > demais extensões (a primeira linguagem fica).
"""

import json
import os
import sys
import urllib.request
from typing import Any

import yaml

URL = "https://raw.githubusercontent.com/github-linguist/linguist/main/lib/linguist/languages.yml"


def build_catalog(data: dict[str, Any]) -> dict[str, Any]:
    """Language list (name, color, candidate tags) and tag -> index map, in linguist precedence order."""
    langs: list[list[Any]] = []
    index: dict[str, int] = {}
    for name, d in data.items():
        index[name] = len(langs)
        color = d.get("color") or (
            data.get(d["group"], {}).get("color") if d.get("group") else None
        )
        cands = [
            name.lower(),
            name.lower().replace(" ", "-"),
            *(a.lower() for a in d.get("aliases", [])),
        ]
        for k in ("ace_mode", "codemirror_mode"):
            if d.get(k) and d[k] != "text":
                cands.append(d[k].lower())
        if d.get("group"):
            cands.append(d["group"].lower())
        cands += [e.lstrip(".").lower() for e in d.get("extensions", [])]
        langs.append([name, color, list(dict.fromkeys(cands))])
    tags: dict[str, int] = {}

    def put(tag: str, i: int) -> None:
        tag = tag.lower()
        if tag and " " not in tag and tag not in tags:
            tags[tag] = i

    for name in data:
        put(name.replace(" ", "-"), index[name])
        if " " not in name:
            put(name, index[name])
    for name, d in data.items():
        for a in d.get("aliases", []):
            put(a, index[name])
    for name, d in data.items():
        ext = d.get("extensions", [])
        if ext:
            put(ext[0].lstrip("."), index[name])
    for name, d in data.items():
        for e in d.get("extensions", [])[1:]:
            put(e.lstrip("."), index[name])
        for f in d.get("interpreters", []):
            put(f, index[name])
    return {"source": URL, "langs": langs, "tags": tags}


def render(catalog: dict[str, Any]) -> str:
    """TypeScript module with the catalog on one line (Biome skips it)."""
    body = json.dumps(catalog, ensure_ascii=False, separators=(",", ":"))
    header = (
        "// Generated by scripts/harness/gen-code-blocks-languages.py from github-linguist languages.yml; do not edit.\n"
        "export interface LanguageCatalog {\n"
        "\tsource: string;\n"
        "\tlangs: [string, string | null, string[]][];\n"
        "\ttags: Record<string, number>;\n"
        "}\n\n"
    )
    return f"{header}// biome-ignore format: generated catalog, one line\nexport const CATALOG: LanguageCatalog = {body};\n"


OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "packages",
    "coding-agent",
    "src",
    "extensions",
    "code-blocks",
    "languages.ts",
)


def main(argv: list[str], out: str = OUT) -> None:
    if len(argv) > 1:
        with open(argv[1], encoding="utf-8") as src:
            raw = src.read()
    else:  # pragma: no cover - network
        with urllib.request.urlopen(URL) as resp:
            raw = resp.read().decode()
    catalog = build_catalog(yaml.safe_load(raw))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(render(catalog))
    langs = catalog["langs"]
    print(
        f"{len(langs)} linguagens, {sum(1 for x in langs if x[1])} com cor, {len(catalog['tags'])} etiquetas -> {out}"
    )


if __name__ == "__main__":
    main(sys.argv)
