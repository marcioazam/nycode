"""Tests for gen-code-blocks-languages.py: catalog order, tag precedence and the generated module."""

import importlib.util
import tempfile
import unittest
from contextlib import redirect_stdout
from io import StringIO
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    "gen_code_blocks_languages",
    Path(__file__).with_name("gen-code-blocks-languages.py"),
)
assert spec is not None and spec.loader is not None
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)

YAML = """\
TypeScript:
  color: "#3178c6"
  aliases: [ts]
  extensions: [".ts", ".cts"]
  ace_mode: typescript
  interpreters: [deno]
JavaScript:
  color: "#f1e05a"
  aliases: [js, node]
  extensions: [".js", ".ts"]
  codemirror_mode: javascript
TSX:
  group: TypeScript
  extensions: [".tsx"]
  ace_mode: text
Shell Session:
  aliases: [console]
  extensions: [".sh-session"]
"""


class BuildCatalog(unittest.TestCase):
    def setUp(self) -> None:
        self.cat = gen.build_catalog(gen.yaml.safe_load(YAML))

    def test_languages_keep_order_color_and_candidates(self) -> None:
        names = [x[0] for x in self.cat["langs"]]
        self.assertEqual(names, ["TypeScript", "JavaScript", "TSX", "Shell Session"])
        ts = self.cat["langs"][0]
        self.assertEqual(ts[1], "#3178c6")
        self.assertEqual(ts[2], ["typescript", "ts", "cts"])
        self.assertEqual(self.cat["langs"][2][1], "#3178c6")  # color from the group
        self.assertIn(
            "typescript", self.cat["langs"][2][2]
        )  # group as candidate, ace_mode text skipped
        self.assertIsNone(self.cat["langs"][3][1])
        self.assertEqual(self.cat["source"], gen.URL)

    def test_tag_precedence_name_alias_primary_extension_rest(self) -> None:
        tags = self.cat["tags"]
        self.assertEqual(tags["typescript"], 0)
        self.assertEqual(
            tags["ts"], 0
        )  # alias of TypeScript wins over the JavaScript extension
        self.assertEqual(tags["js"], 1)
        self.assertEqual(tags["node"], 1)
        self.assertEqual(tags["tsx"], 2)
        self.assertEqual(tags["cts"], 0)
        self.assertEqual(tags["deno"], 0)
        self.assertEqual(tags["shell-session"], 3)
        self.assertNotIn("shell session", tags)


class RenderAndMain(unittest.TestCase):
    def test_render_is_one_line_module(self) -> None:
        out = gen.render(
            {"source": "s", "langs": [["A", None, ["a"]]], "tags": {"a": 0}}
        )
        self.assertTrue(
            out.startswith(
                "// Generated by scripts/harness/gen-code-blocks-languages.py"
            )
        )
        self.assertIn("// biome-ignore format: generated catalog, one line\n", out)
        self.assertTrue(
            out.endswith(
                'export const CATALOG: LanguageCatalog = {"source":"s","langs":[["A",null,["a"]]],"tags":{"a":0}};\n'
            )
        )

    def test_main_writes_the_module_from_a_local_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp, "languages.yml")
            src.write_text(YAML, encoding="utf-8")
            dest = Path(tmp, "languages.ts")
            buf = StringIO()
            with redirect_stdout(buf):
                gen.main(["gen", str(src)], out=str(dest))
            text = dest.read_text(encoding="utf-8")
        self.assertIn('"TypeScript","#3178c6"', text)
        self.assertIn("4 linguagens, 3 com cor", buf.getvalue())


if __name__ == "__main__":
    unittest.main()
