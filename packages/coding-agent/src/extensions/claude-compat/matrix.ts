export const COMMANDS: readonly CmdRow[] = rows.map(([name, aliases, kind, status, nycode]) => ({
	name,
	aliases: aliases ? aliases.split(" ") : [],
	kind,
	status,
	nycode,
}));

import { SHORTCUTS } from "./shortcuts.ts";

const cell = (s: string) => s.replaceAll("|", "\\|");

/** Markdown da matriz completa (docs/claude-code-compat.md). */
export function renderMatrix(): string {
	const c = COMMANDS.map(
		(r) =>
			`| /${r.name} | ${r.aliases.map((a) => `/${a}`).join(" ") || "–"} | ${r.kind} | ${r.status} | ${cell(r.nycode)} |`,
	);
	const k = SHORTCUTS.map((r) => `| ${cell(r.key)} | ${cell(r.claude)} | ${r.status} | ${cell(r.nycode)} |`);
	return [
		"### Comandos",
		"",
		"| Claude | Aliases | Tipo | Status | nycode |",
		"|---|---|---|---|---|",
		...c,
		"",
		"### Atalhos",
		"",
		"| Tecla | Claude | Status | nycode |",
		"|---|---|---|---|",
		...k,
		"",
	].join("\n");
}
